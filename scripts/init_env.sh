#!/bin/bash
# init_env.sh
# Creates .env with a fresh random password for every account, unless a usable
# .env already exists. Nothing secret is ever committed: .env is in .gitignore.
#
#   bash scripts/init_env.sh
#
# An existing .env that still contains the "change-me" placeholders from
# .env.example is rejected instead of being used: a documented password is
# not a password.

set -euo pipefail
umask 077   # .env is readable by its owner only

cd "$(dirname "$0")/.."

if [ -f .env ]; then
    if grep -q 'change-me' .env; then
        echo "ERROR: .env still contains the 'change-me' placeholders." >&2
        echo "       Delete it (rm .env) and run this script again to get random passwords." >&2
        exit 1
    fi
    echo ".env already exists - keeping it."
    exit 0
fi

random_password() {
    # 24 hex characters = 96 bits of randomness; only [0-9a-f], so it is safe
    # inside SQL quotes (see sql/04_users.sh).
    openssl rand -hex 12
}

{
    echo "# Generated by scripts/init_env.sh - local demo passwords. Never commit this file."
    echo "MARIADB_ROOT_PASSWORD=$(random_password)"
    echo "STUDENT_PASSWORD=$(random_password)"
    echo "PROFESSOR_PASSWORD=$(random_password)"
    echo "FINANCE_PASSWORD=$(random_password)"
    echo "ADMIN_PASSWORD=$(random_password)"
} > .env

echo "Created .env with random passwords."
