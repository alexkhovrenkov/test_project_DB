class Lab:
    """A throw-away database plus helpers to create roles and accounts around it."""

    def __init__(self, admin_connection):
        self.admin = admin_connection
        self.suffix = secrets.token_hex(4)
        self.db = f"t_lab_{self.suffix}"
        self.users, self.roles, self.public_denies = [], [], []
        self.run(f"CREATE DATABASE {self.db}")
        self.run(f"CREATE TABLE {self.db}.t (id INT PRIMARY KEY, pub VARCHAR(20), secret VARCHAR(20))")
        self.run(f"CREATE TABLE {self.db}.u (id INT PRIMARY KEY, v VARCHAR(20))")
        self.run(f"INSERT INTO {self.db}.t VALUES (1, 'public-1', 'secret-1')")
        self.run(f"INSERT INTO {self.db}.u VALUES (1, 'value-1')")

    # Names below are generated by this class (hex + fixed words), never user input,
    # so building identifiers with f-strings is safe here; values still use parameters.
    def run(self, sql, params=None):
        return run_query(self.admin, sql, params)

    def role(self, name):
        full = f"{name}_{self.suffix}"
        self.run(f"CREATE ROLE {full}")
        self.roles.append(full)
        return full

    def account(self, name, roles=(), default_role=None):
        """Create an ED25519 account; returns (user name, password)."""
        user, password = f"{name}_{self.suffix}", strong_password()
        # '%%' = a literal '%' (the host part), because this statement has a %s parameter.
        self.run(f"CREATE USER {user}@'%%' IDENTIFIED VIA ed25519 USING PASSWORD(%s)", (password,))
        self.users.append(user)
        for role in roles:
            self.run(f"GRANT {role} TO {user}@'%'")
        if default_role:
            self.run(f"SET DEFAULT ROLE {default_role} FOR {user}@'%'")
        return user, password

    @contextmanager
    def session(self, account):
        user, password = account
        connection = connect(user, password, database=None)
        try:
            yield connection
        finally:
            connection.close()

    def public_deny(self, privilege_target):
        """DENY SELECT ON <target> TO PUBLIC, remembered so cleanup lifts it."""
        self.run(f"DENY SELECT ON {privilege_target} TO PUBLIC")
        self.public_denies.append(privilege_target)

    def cleanup(self):
        for target in self.public_denies:
            self.run(f"REVOKE DENY SELECT ON {target} FROM PUBLIC")
        self.run(f"DROP DATABASE IF EXISTS {self.db}")
        for user in self.users:
            self.run(f"DROP USER IF EXISTS {user}@'%'")
        for role in self.roles:
            self.run(f"DROP ROLE IF EXISTS {role}")


